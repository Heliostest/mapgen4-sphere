import {spawn} from 'node:child_process';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve,basename} from 'node:path';
const folder='docs/evidence/earth-speedy-budgets-sst-20261012',runtime='build/earth-speedyweather';
const script=process.argv[2];if(!script)throw Error('Supply Julia script');
const env={...process.env,JULIA_DEPOT_PATH:resolve(`${runtime}/depot`),JULIA_NUM_THREADS:'2',OPENBLAS_NUM_THREADS:'1'};
const args=['--startup-file=no','--project=docs/evidence/earth-speedyweather-20261012/julia-env',script];
const startedUTC=new Date().toISOString();
const hash=b=>createHash('sha256').update(b).digest('hex');
const launchFiles=[script,`${folder}/components.jl`,`${folder}/corrections.jl`,`${folder}/protocol.md`];
const sourceBefore=Object.fromEntries(await Promise.all(launchFiles.map(async p=>[p,hash(await readFile(p))])));
const child=spawn(resolve(`${runtime}/runtime/julia-1.12.7/bin/julia.exe`),args,{env,windowsHide:true});
let output='';child.stdout.on('data',c=>output+=c);child.stderr.on('data',c=>output+=c);
const code=await new Promise((resolve,reject)=>{child.on('error',reject);child.on('close',resolve);});
const name=process.env.SPEEDY_CASE??basename(script,'.jl');await writeFile(`${folder}/${name}-native.log`,output);
const sourceAfter=Object.fromEntries(await Promise.all(launchFiles.map(async p=>[p,hash(await readFile(p))])));
const result={startedUTC,completedUTC:new Date().toISOString(),script,sourceBefore,sourceAfter,sourceUnchanged:JSON.stringify(sourceBefore)===JSON.stringify(sourceAfter),args,code};
await writeFile(`${folder}/${name}-native-status.json`,JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));console.log(output.slice(-2300));process.exitCode=code;
