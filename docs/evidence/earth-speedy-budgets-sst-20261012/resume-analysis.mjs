import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const folder='docs/evidence/earth-speedy-budgets-sst-20261012',out='build/earth-speedy-budgets-sst';
const hash=b=>createHash('sha256').update(b).digest('hex');
const files=[`${folder}/acceptance.json`,`${out}/comparison-display.json`];
const before=await Promise.all(files.map(async path=>({path,sha256:hash(await readFile(path))})));
const b=await build({entryPoints:[`${folder}/analyze.mjs`],outfile:`${out}/analyze.bundle.mjs`,bundle:true,platform:'node',format:'esm',metafile:true});
await writeFile(`${out}/analyze-metafile.json`,JSON.stringify(b.metafile,null,2));
const result=spawnSync(process.execPath,[`${out}/analyze.bundle.mjs`],{encoding:'utf8',windowsHide:true,maxBuffer:8*1024*1024});
await writeFile(`${folder}/analysis-result.log`,result.stdout+result.stderr);assert.equal(result.status,0);
const after=await Promise.all(files.map(async path=>({path,sha256:hash(await readFile(path))})));
assert.deepEqual(after,before,'Rebuilt current source must reproduce recovered analysis exactly');
const sources=await Promise.all(Object.keys(b.metafile.inputs).map(async path=>({path,sha256:hash(await readFile(path))})));
const verification={createdUTC:new Date().toISOString(),passed:true,exitCode:result.status,outputs:after,sourceBindings:sources};
await writeFile(`${folder}/resume-analysis-verification.json`,JSON.stringify(verification,null,2)+'\n');
console.log(JSON.stringify(verification,null,2));
