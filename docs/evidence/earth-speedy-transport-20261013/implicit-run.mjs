import {spawn} from 'node:child_process';
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
const folder='docs/evidence/earth-speedy-transport-20261013';
const script=process.argv[2]??`${folder}/implicit-test.jl`;
const label=process.env.IMPLICIT_LABEL??'native-red';
const paths=[script,`${folder}/implicit-corrected.jl`,...['time_stepping/implicit/implicit_primitive_equations.jl','dynamics/tendencies.jl','dynamics/vertical_advection.jl','dynamics/adiabatic_conversion.jl'].map(p=>`build/earth-speedyweather/depot/packages/SpeedyWeather/qRu16/src/${p}`)];
const hashes=async()=>Object.fromEntries(await Promise.all(paths.map(async p=>[p,createHash('sha256').update(await readFile(p)).digest('hex')])));
const before=await hashes(),startedUTC=new Date().toISOString();
const env={...process.env,JULIA_DEPOT_PATH:resolve('build/earth-speedyweather/depot'),JULIA_NUM_THREADS:'2',OPENBLAS_NUM_THREADS:'1',MASS_IMPLEMENTATION:'fixed'};
const args=['--startup-file=no','--project=docs/evidence/earth-speedyweather-20261012/julia-env',script];
const child=spawn(resolve('build/earth-speedyweather/runtime/julia-1.12.7/bin/julia.exe'),args,{env,windowsHide:true});
let output='';child.stdout.on('data',c=>output+=c);child.stderr.on('data',c=>output+=c);
const code=await new Promise((resolve,reject)=>{child.on('close',resolve);child.on('error',reject);});
const after=await hashes();
await writeFile(`${folder}/implicit-${label}.log`,output);
await writeFile(`${folder}/implicit-${label}-status.json`,JSON.stringify({startedUTC,completedUTC:new Date().toISOString(),script,args,code,before,after,sourceUnchanged:JSON.stringify(before)===JSON.stringify(after)},null,2)+'\n');
console.log(JSON.stringify({label,code,sourceUnchanged:JSON.stringify(before)===JSON.stringify(after)}));console.log(output.slice(-10000));process.exitCode=code;
