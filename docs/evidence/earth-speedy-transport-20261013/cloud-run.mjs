import {spawn} from 'node:child_process';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
const folder='docs/evidence/earth-speedy-transport-20261013';
const implementation=process.argv[2]??'native';
if(!['native','precip_only','full'].includes(implementation))throw Error('invalid implementation');
const paths=[`${folder}/cloud-test.jl`,...(implementation!=='native'?[`${folder}/cloud-correction.jl`]:[])];
const hash=async()=>Object.fromEntries(await Promise.all(paths.map(async p=>[p,createHash('sha256').update(await readFile(p)).digest('hex')])));
const before=await hash(),startedUTC=new Date().toISOString();
const args=['--startup-file=no','--project=docs/evidence/earth-speedyweather-20261012/julia-env',paths[0]];
const child=spawn(resolve('build/earth-speedyweather/runtime/julia-1.12.7/bin/julia.exe'),args,{windowsHide:true,env:{...process.env,JULIA_DEPOT_PATH:resolve('build/earth-speedyweather/depot'),JULIA_NUM_THREADS:'2',OPENBLAS_NUM_THREADS:'1',CLOUD_IMPLEMENTATION:implementation}});
let output='';child.stdout.on('data',b=>output+=b);child.stderr.on('data',b=>output+=b);
const exitCode=await new Promise((res,rej)=>{child.on('error',rej);child.on('close',res);});
const after=await hash();
const result={implementation,exitCode,startedUTC,completedUTC:new Date().toISOString(),sourceBefore:before,sourceAfter:after,sourceUnchanged:JSON.stringify(before)===JSON.stringify(after)};
await writeFile(`${folder}/cloud-${implementation}.log`,output);
await writeFile(`${folder}/cloud-${implementation}.json`,JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));console.log(output);process.exitCode=exitCode;
